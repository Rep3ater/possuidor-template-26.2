$files = Get-ChildItem -Recurse $commonSrc -Filter *.java
$count = 0
foreach ($f in $files) {
    if ($f.FullName -like "*\mixin\*") { continue }
    if ($f.FullName -like "*\advancement\criterion\*") { continue } # already ported manually

    $rel = $f.FullName.Substring($commonSrc.Length + 1)
    $dest = Join-Path $destRoot $rel
    $destDir = Split-Path $dest -Parent
    if (-not (Test-Path $destDir)) { New-Item -ItemType Directory -Force -Path $destDir | Out-Null }
    
    $content = Get-Content $f.FullName -Raw -Encoding UTF8
    foreach ($rep in $importReplacements) {
        $content = [regex]::Replace($content, "import\s+(static\s+)?" + $rep[0], "import `$1" + $rep[1])
    }
    foreach ($rep in $wordReplacements) {
        $content = [regex]::Replace($content, $rep[0], $rep[1])
    }
    [System.IO.File]::WriteAllText($dest, $content, (New-Object System.Text.UTF8Encoding($false)))
    $count++
}
Write-Host "Migrated $count requiem common files to $destRoot"
